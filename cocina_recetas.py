"""Cocina v2: las 30 recetas (una por nivel 1..30). Datos puros, sin dibujar.

Convenciones de los pasos (spec de cocina_base):
  h       habilidad
  ing     objeto de catalogo o pseudo-ingrediente sobre el que actua el paso (en espolvorear/untar/decorar/cucharear/
          verter es lo que se echa; `sobre` es el destino)
  ings    (combinar) lista de ingredientes que se juntan en el cuenco `tazon`
  herr    herramienta (cursor): cuchillo, tijera, pelador, rallador, rodillo, tenedor, molde, manos...
  tazon   cuenco "A".."F" donde queda lo preparado (los cuencos se reutilizan una vez usado su contenido)
Orden: preparar crudos -> combinar/montar -> cocinar -> servir. Fuentes en RECETAS_INVESTIGACION.md.
"""


def P(h, ing=None, ings=None, sobre=None, herr=None, tazon=None):
    d = dict(h=h)
    if ing:
        d["ing"] = ing
    if ings:
        d["ings"] = list(ings)
    if sobre:
        d["sobre"] = sobre
    if herr:
        d["herr"] = herr
    if tazon:
        d["tazon"] = tazon
    return d


def R(id, nombre, nivel, mats, color, cont, desc, pasos, basica=False):
    return dict(id=id, nombre=nombre, nivel=nivel, basica=basica, mats=mats, color=color, cont=cont, desc=desc,
                pasos=pasos)


